-- Jalankan SQL ini di Supabase Dashboard > SQL Editor.
-- Database 'postgres' sudah otomatis dibuat saat project Supabase dibuat.
-- Script ini menyiapkan tabel antrean dan akun petugas.

CREATE TABLE IF NOT EXISTS public.antrean (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue_number INTEGER NOT NULL,
    nama VARCHAR(100) NOT NULL,
    keperluan VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'waiting'
        CONSTRAINT antrean_status_check CHECK (status IN ('waiting', 'called', 'done', 'skipped')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    service_date DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (service_date, queue_number)
);

CREATE INDEX IF NOT EXISTS idx_antrean_service_date_status
ON public.antrean (service_date, status, queue_number);

-- Peningkatan kompatibel dengan tabel antrean versi sebelumnya.
CREATE TABLE IF NOT EXISTS public.app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  nim VARCHAR(20) NOT NULL UNIQUE CHECK (nim ~ '^[0-9]{5,20}$'),
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.user_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_sessions_user ON public.user_sessions(user_id);
ALTER TABLE public.antrean ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES public.app_users(id);
ALTER TABLE public.antrean ADD COLUMN IF NOT EXISTS nim VARCHAR(20);
ALTER TABLE public.antrean ADD COLUMN IF NOT EXISTS unique_code UUID NOT NULL DEFAULT gen_random_uuid();
CREATE UNIQUE INDEX IF NOT EXISTS idx_antrean_unique_code ON public.antrean(unique_code);
CREATE UNIQUE INDEX IF NOT EXISTS idx_antrean_active_user ON public.antrean(service_date, user_id) WHERE status IN ('waiting', 'called');
-- Semua akses aplikasi melalui backend PostgreSQL, bukan Data API publik.
ALTER TABLE public.app_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.antrean ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.app_users, public.user_sessions, public.antrean FROM anon, authenticated;

-- Username menggantikan NIM untuk login petugas. NIM lama menjadi username awal.
BEGIN;
ALTER TABLE public.app_users ALTER COLUMN nim DROP NOT NULL;
ALTER TABLE public.app_users ADD COLUMN IF NOT EXISTS username VARCHAR(32)
  CHECK (username ~ '^[a-z0-9._-]{3,32}$');
UPDATE public.app_users SET username = nim WHERE role = 'admin' AND username IS NULL AND nim IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_app_users_username ON public.app_users(username);
COMMIT;

-- Jalankan satu kali di SQL Editor Supabase untuk instalasi yang sudah ada.
-- queue_number tetap menjadi urutan kedatangan untuk pemanggilan satu loket.
BEGIN;
LOCK TABLE public.antrean IN ACCESS EXCLUSIVE MODE;
ALTER TABLE public.antrean DROP CONSTRAINT IF EXISTS antrean_status_check;
ALTER TABLE public.antrean ADD CONSTRAINT antrean_status_check
  CHECK (status IN ('waiting', 'called', 'done', 'skipped'));

ALTER TABLE public.antrean ADD COLUMN IF NOT EXISTS service_number INTEGER;
WITH numbered AS (
  SELECT id, ROW_NUMBER() OVER (
    PARTITION BY service_date, keperluan ORDER BY queue_number, id
  )::integer AS number
  FROM public.antrean
)
UPDATE public.antrean a SET service_number = n.number
FROM numbered n WHERE a.id = n.id AND a.service_number IS NULL;
ALTER TABLE public.antrean ALTER COLUMN service_number SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_antrean_service_number
  ON public.antrean (service_date, keperluan, service_number);
COMMIT;
